/** The language the app shows. */
export const language = ref<Locale>("en");
/** The BCP-47 tag for `Intl` formatting (dates, numbers) in that language. */
export const intlLocale = ref("en-GB");

/** Follows Haven's locale (`launchContext.locale`, `onLocaleChange`). */
export function setLocale(locale: string | undefined | null) {
  const next = resolveLocale(locale);
  language.value = next;
  intlLocale.value = intlTagFor(next, locale);
  if (typeof document !== "undefined") {
    // Native controls (date inputs) and screen readers follow the page language.
    document.documentElement.lang = intlLocale.value;
  }
}

/** Keeps a regional tag Haven sends for the chosen language ("de-AT"); a bare language gets a default region. */
function intlTagFor(chosen: Locale, tag: string | undefined | null): string {
  const defaults: Record<Locale, string> = {
    en: "en-GB", de: "de-DE", es: "es-ES", fr: "fr-FR", it: "it-IT", nb: "nb-NO", nl: "nl-NL", pl: "pl-PL",
  };
  const trimmed = (tag ?? "").trim();
  if (trimmed.includes("-") && resolveLocale(trimmed) === chosen) {
    try {
      return Intl.getCanonicalLocales(trimmed)[0] ?? defaults[chosen];
    } catch {
      return defaults[chosen];
    }
  }
  return defaults[chosen];
}

function fill(text: string, params: Record<string, string | number>): string {
  return text.replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? ""));
}

export function t(key: MessageKey, params: Record<string, string | number> = {}): string {
  return fill(messages[language.value][key], params);
}

/**
 * A message split around one placeholder, for markup inside the sentence
 * (`before<em>…</em>after`) wherever the language puts it.
 */
export function tSplit(key: MessageKey, placeholder: string, params: Record<string, string | number> = {}) {
  const marker = "\u0000";
  const [before = "", after = ""] = t(key, { ...params, [placeholder]: marker }).split(marker);
  return { before, after };
}

/** A message that depends on a number: picks the plural form for `count` and fills `{count}`. */
export function tn(key: PluralKey, count: number, params: Record<string, string | number> = {}): string {
  const forms: PluralForms = messages[language.value][key];
  const category = new Intl.PluralRules(language.value).select(count);
  return fill(forms[category] ?? forms.other, { ...params, count });
}

