function parseDate(value: string | number | null | undefined): Date | null {
  if (value === null || value === undefined || value === "") return null;
  const date = new Date(value);
  return Number.isNaN(date.getTime()) ? null : date;
}

/** A date (start, due) in the current language, or `null` when there is none. */
export function formatDate(value: string | null | undefined): string | null {
  const date = parseDate(value);
  return date ? date.toLocaleDateString(intlLocale.value, { dateStyle: "medium" }) : null;
}

/** A point in time (time travel) in the current language. */
export function formatDateTime(value: string | number | null | undefined): string {
  const date = parseDate(value);
  return date ? date.toLocaleString(intlLocale.value, { dateStyle: "medium", timeStyle: "short" }) : "";
}

/** A file size with the unit names and decimal separator of the current language. */
export function formatFileSize(size: number): string {
  const units = ["byte", "kilobyte", "megabyte", "gigabyte", "terabyte"] as const;
  let value = Number.isFinite(size) ? Math.max(0, size) : 0;
  let unitIndex = 0;
  while (value >= 1024 && unitIndex < units.length - 1) {
    value /= 1024;
    unitIndex += 1;
  }
  const fractionDigits = unitIndex === 0 || value >= 100 ? 0 : value >= 10 ? 1 : 2;
  return new Intl.NumberFormat(intlLocale.value, {
    style: "unit",
    unit: units[unitIndex],
    unitDisplay: "short",
    maximumFractionDigits: fractionDigits,
  }).format(unitIndex === 0 ? Math.round(value) : value);
}

