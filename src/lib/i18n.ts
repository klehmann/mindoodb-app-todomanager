/**
 * The app's strings in every language Haven speaks.
 *
 * English is the reference: `Messages` is derived from the `en` table, and the whole
 * table is checked with `satisfies Record<Locale, Messages>`, so a key missing in (or
 * added only to) one language fails the type check. `i18n.test.ts` also compares every
 * language's `{placeholders}` and plural forms with English.
 *
 * A message is either a string or a set of plural forms (`Intl.PluralRules`
 * categories, `other` required) for `tn()`. French texts carry a non-breaking space
 * (U+00A0) before : ; ? ! and inside « »; the test checks it.
 *
 * Agent tool descriptions, results and undo step labels (which agents read through
 * `todo_history`) stay English on purpose: they are written for the model, not the user.
 */
